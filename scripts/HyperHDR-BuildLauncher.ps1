# Build the browser's executable template with the Windows .NET Framework compiler.
# Windows PowerShell 5.1+. No package downloads required.
$ErrorActionPreference = 'Stop'
$repositoryRoot = Split-Path -Parent $PSScriptRoot
$compiler = Join-Path $env:WINDIR 'Microsoft.NET\Framework64\v4.0.30319\csc.exe'
if (-not (Test-Path -LiteralPath $compiler)) {
    $compiler = Join-Path $env:WINDIR 'Microsoft.NET\Framework\v4.0.30319\csc.exe'
}
$source = Join-Path $PSScriptRoot 'HyperHDR-DayCycle-Launcher.cs'
$temporaryExe = Join-Path ([IO.Path]::GetTempPath()) ('HyperHDR-Launcher-' + [Guid]::NewGuid().ToString('N') + '.exe')
try {
    & $compiler /nologo /target:winexe /platform:anycpu /optimize+ /reference:System.Windows.Forms.dll /reference:System.Drawing.dll "/out:$temporaryExe" $source
    if ($LASTEXITCODE -ne 0) { throw 'Launcher compilation failed.' }
    $base64 = [Convert]::ToBase64String([IO.File]::ReadAllBytes($temporaryExe))
    $output = Join-Path $repositoryRoot 'app\launcher-template.js'
    [IO.File]::WriteAllText($output, "// Generated by scripts/HyperHDR-BuildLauncher.ps1. Do not edit.`nwindow.hyperhdrLauncherBase64 = '$base64';`n", [Text.Encoding]::ASCII)
    Write-Host "Built launcher template: $output"
}
finally {
    if (Test-Path -LiteralPath $temporaryExe) { Remove-Item -LiteralPath $temporaryExe }
}
